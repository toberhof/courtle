// ── Intl Date Formatting ──

function fmtTime(t) {
  if (!t) return '';
  let h, m;
  if (t instanceof Date) {
    h = t.getHours();
    m = String(t.getMinutes()).padStart(2, '0');
  } else {
    const parts = String(t).split(':');
    if (parts.length < 2) return String(t);
    h = parseInt(parts[0], 10);
    m = parts[1].slice(0, 2);
  }
  const timeFmt = (window.S && window.S.cfg && window.S.cfg.time_format) || '24h';
  if (timeFmt === '12h') {
    const ampm = h >= 12 ? 'PM' : 'AM';
    const h12 = h % 12 === 0 ? 12 : h % 12;
    return `${h12}:${m} ${ampm}`;
  }
  return `${String(h).padStart(2, '0')}:${m}`;
}

function fmtDate(d) {
  if (!d) return '';
  let dt;
  if (d instanceof Date) {
    dt = d;
  } else if (/T| /.test(d)) {
    dt = new Date(d);
  } else {
    dt = new Date(d + 'T12:00:00');
  }
  if (Number.isNaN(dt.getTime())) return String(d);
  const day = String(dt.getDate()).padStart(2, '0');
  const month = String(dt.getMonth() + 1).padStart(2, '0');
  const year = dt.getFullYear();
  const fmt = (window.S && window.S.cfg && window.S.cfg.date_format) || 'dmy';
  if (fmt === 'mdy') {
    return `${month}/${day}/${year}`;
  } else if (fmt === 'ymd') {
    return `${year}-${month}-${day}`;
  } else {
    return `${day}.${month}.${year}`;
  }
}

function fmtDateLong(d) {
  if (!d) return '';
  let dt;
  if (d instanceof Date) {
    dt = d;
  } else {
    dt = new Date(d + 'T12:00:00');
  }
  if (Number.isNaN(dt.getTime())) return String(d);
  const locale = getLocale();
  const weekday = new Intl.DateTimeFormat(locale, { weekday: 'short' }).format(dt).replace('.', '');
  const fmt = (window.S && window.S.cfg && window.S.cfg.date_format) || 'dmy';
  const day = String(dt.getDate());
  const month = new Intl.DateTimeFormat(locale, { month: 'short' }).format(dt).replace('.', '');
  const year = String(dt.getFullYear()).slice(-2);
  
  if (fmt === 'mdy') {
    return `${weekday}, ${month} ${day} ${year}`;
  } else if (fmt === 'ymd') {
    return `${weekday}, ${year}-${String(dt.getMonth() + 1).padStart(2, '0')}-${day.padStart(2, '0')}`;
  } else {
    return `${weekday}, ${day}. ${month} ${year}`;
  }
}

function fmtDateTime(d) {
  if (!d) return '';
  let dt;
  if (d instanceof Date) {
    dt = d;
  } else {
    const normalized = d.includes('T') ? d : d.replace(' ', 'T');
    dt = new Date(normalized);
  }
  if (Number.isNaN(dt.getTime())) return String(d);
  const datePart = fmtDate(dt);
  const timePart = fmtTime(dt);
  return `${datePart} ${timePart}`;
}

function fmtDateTimeFull(d) {
  return fmtDateTime(d);
}

function fmtDateTimeShort(d) {
  if (!d) return '';
  let dt;
  if (d instanceof Date) {
    dt = d;
  } else {
    const normalized = d.includes('T') ? d : d.replace(' ', 'T');
    dt = new Date(normalized);
  }
  if (Number.isNaN(dt.getTime())) return String(d);
  const datePart = fmtDate(dt);
  const timePart = fmtTime(dt);
  return `${datePart} - ${timePart}`;
}

function fmtDateTimeHistory(d) {
  return fmtDateTime(d);
}

// ── Currency Formatting ──

function fmtCurrency(v) {
  const currency = (window.S && window.S.cfg && window.S.cfg.currency) || '€';
  const isSymbol = currency.length <= 3;
  const abs = Math.abs(v);
  const formatted = abs.toFixed(2).replace('.', localeUsesComma() ? ',' : '.');
  const sign = v < 0 ? (localeUsesComma() ? '–' : '-') : '';
  if (isSymbol) {
    return sign + formatted + ' ' + currency;
  }
  return sign + formatted + ' ' + currency;
}

function localeUsesComma() {
  const locale = getLocale();
  return locale === 'de' || locale === 'es' || locale === 'it' || locale === 'fr' || locale === 'pt';
}

