// ── Core Functions ──

function t(key, params) {
  const locale = getLocale();
  let msg = I18N.dict[locale]?.[key] || I18N.dict.en?.[key] || key;
  if (params) {
    Object.keys(params).forEach(k => {
      msg = msg.replace('{' + k + '}', params[k]);
    });
  }
  return msg;
}

function getLocale() {
  // 1. Player has explicit language set
  if (window.S && window.S.players && window.guestId) {
    const me = window.S.players.find(p => p.id == window.guestId);
    if (me && me.language) return me.language;
  }
  // 2. Admin system default
  if (window.S && window.S.cfg && window.S.cfg.system_language) {
    return window.S.cfg.system_language;
  }
  // 3. Browser language
  const browser = (navigator.language || 'en').slice(0, 2).toLowerCase();
  if (['de', 'en', 'es', 'it', 'fr', 'pt'].includes(browser)) return browser;
  // 4. Fallback
  return 'en';
}

function setLocale(lang) {
  if (lang === 'auto' || lang === null || lang === '') {
    lang = null;
  }
  I18N.current = lang;
  // Save to server if logged in
  if (window.guestId && window.apiFetch) {
    window.apiFetch('PUT', '/players/' + window.guestId, { language: lang }).catch(() => {});
  }
  // Update state
  if (window.S && window.S.players && window.guestId) {
    const me = window.S.players.find(p => p.id == window.guestId);
    if (me) me.language = lang;
  }
  // Apply
  document.documentElement.lang = getLocale();
  applyTranslations();
  // Refresh theme toggle icons (they use innerHTML, not data-i18n)
  if (typeof window.applyThemeUI === 'function') {
    window.applyThemeUI(document.documentElement.getAttribute('data-theme-mode') || 'auto');
  }
  // Re-render all views with new locale
  window._lastSessionHash = null; // Force session cards to re-render with new locale
  if (typeof window.renderSessions === 'function') window.renderSessions();
  if (window.isAdmin) {
    if (typeof window.renderAll === 'function') window.renderAll();
  } else {
    if (typeof window.renderMyHistory === 'function') window.renderMyHistory();
    if (typeof window.renderMyTransactions === 'function') window.renderMyTransactions();
  }
  // Re-render Lucide icons after DOM updates
  if (window.lucide && typeof window.lucide.createIcons === 'function') {
    setTimeout(() => window.lucide.createIcons(), 50);
  }
}

function applyTranslations() {
  const locale = getLocale();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = t(key);
    }
  });
  // Also handle data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      el.placeholder = t(key);
    }
  });
  // Handle data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) {
      el.title = t(key);
    }
  });
  // Handle data-i18n-html (for HTML content)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (key) {
      el.innerHTML = t(key);
    }
  });
  // Handle data-i18n-aria-label
  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria-label');
    if (key) {
      el.setAttribute('aria-label', t(key));
    }
  });
  document.documentElement.lang = locale;
}

